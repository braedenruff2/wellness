#!/usr/bin/env node
/* Builds app/www/modules/faith/content.js from content/*.cjs and the World English Bible text in source/.
   Usage: node tools/build-content.cjs [--check]   (--check: fail if content.js is out of date) */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

const BOOKS = {
  GEN: 'Genesis', EXO: 'Exodus', LEV: 'Leviticus', NUM: 'Numbers', DEU: 'Deuteronomy', JOS: 'Joshua', JDG: 'Judges',
  RUT: 'Ruth', '1SA': '1 Samuel', '2SA': '2 Samuel', '1KI': '1 Kings', '2KI': '2 Kings', '1CH': '1 Chronicles',
  '2CH': '2 Chronicles', EZR: 'Ezra', NEH: 'Nehemiah', EST: 'Esther', JOB: 'Job', PSA: 'Psalm', PRO: 'Proverbs',
  ECC: 'Ecclesiastes', SOL: 'Song of Songs', ISA: 'Isaiah', JER: 'Jeremiah', LAM: 'Lamentations', EZE: 'Ezekiel',
  DAN: 'Daniel', HOS: 'Hosea', JOE: 'Joel', AMO: 'Amos', OBA: 'Obadiah', JON: 'Jonah', MIC: 'Micah', NAH: 'Nahum',
  HAB: 'Habakkuk', ZEP: 'Zephaniah', HAG: 'Haggai', ZEC: 'Zechariah', MAL: 'Malachi', MAT: 'Matthew', MAR: 'Mark',
  LUK: 'Luke', JOH: 'John', ACT: 'Acts', ROM: 'Romans', '1CO': '1 Corinthians', '2CO': '2 Corinthians',
  GAL: 'Galatians', EPH: 'Ephesians', PHI: 'Philippians', COL: 'Colossians', '1TH': '1 Thessalonians',
  '2TH': '2 Thessalonians', '1TI': '1 Timothy', '2TI': '2 Timothy', TIT: 'Titus', PHM: 'Philemon', HEB: 'Hebrews',
  JAM: 'James', '1PE': '1 Peter', '2PE': '2 Peter', '1JO': '1 John', '2JO': '2 John', '3JO': '3 John', JUD: 'Jude',
  REV: 'Revelation'
};

function loadBible(file) {
  const map = new Map();
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^(\w{3}) (\d+):(\d+) (.*)$/.exec(line);
    if (m) map.set(`${m[1]} ${m[2]}:${m[3]}`, m[4].trim());
  }
  return map;
}

/* Psalm titles ("For the Chief Musician. A Psalm by David.") come first in verse 1 in this file.
   source/psalm-titles.json has each title exactly (taken from the USFM edition's \\d lines). */
const TITLES = JSON.parse(fs.readFileSync(path.join(ROOT, 'source', 'psalm-titles.json'), 'utf8'));

function parseRef(ref) {
  const m = /^(\w{3}) (\d+):(\d+)(?:-(\d+))?$/.exec(ref);
  if (!m) throw new Error('Bad reference: ' + ref);
  const book = m[1], ch = +m[2], a = +m[3], b = m[4] ? +m[4] : a;
  if (!BOOKS[book]) throw new Error('Unknown book in ' + ref);
  if (b < a) throw new Error('Backwards range: ' + ref);
  return { book, ch, a, b };
}

function passage(bible, ref) {
  const r = parseRef(ref);
  const verses = [];
  let heading = '';
  for (let v = r.a; v <= r.b; v++) {
    let t = bible.get(`${r.book} ${r.ch}:${v}`);
    if (t == null) throw new Error('Missing verse ' + `${r.book} ${r.ch}:${v}` + ' (in ' + ref + ')');
    if (r.book === 'PSA' && v === 1) {
      const title = TITLES[r.ch];
      if (title && t.startsWith(title)) { heading = title; t = t.slice(title.length).trim(); }
    }
    verses.push({ v, t });
  }
  const label = `${BOOKS[r.book]} ${r.ch}:${r.a}${r.b !== r.a ? '-' + r.b : ''}`;
  return { ref, label, heading, verses };
}

function plain(p) { return p.verses.map((x) => x.t).join(' '); }

/* For a verse quoted inside a spoken line: drop quotation marks that open or close outside it. */
function trimQuotes(t) {
  return t.replace(/^[“‘"']+/, '').replace(/[”"]+$/, '').replace(/([.!?])’$/, '$1');
}

function build() {
  const bible = loadBible(path.join(ROOT, 'source', 'engwebp_vpl.txt'));
  const delCache = (p) => { delete require.cache[require.resolve(p)]; return require(p); };
  const src = delCache(path.join(ROOT, 'content', 'days-src.cjs'));
  const practices = delCache(path.join(ROOT, 'content', 'practices-src.cjs'));
  const days = src.days.map((d) => {
    const passages = d.refs.map((r) => passage(bible, r));
    return Object.assign({}, d, { passages, label: passages.map((p) => p.label).join(', ') });
  });
  const prs = practices.map((p) => {
    const refs = [];
    const steps = p.steps.map((s) => Object.assign({}, s, {
      say: s.say.replace(/\{\{([^}]+)\}\}/g, (all, ref) => {
        if (ref === 'TODAY') return all;
        const ps = passage(bible, ref);
        refs.push(ps.label);
        return trimQuotes(plain(ps)) + ' (' + ps.label + ')';
      })
    }));
    return Object.assign({}, p, { steps, refs });
  });
  const out = {
    translation: 'World English Bible (public domain)',
    weeks: src.weeks,
    days,
    practices: prs
  };
  return '/* Generated by tools/build-content.cjs from content/*.cjs and source/engwebp_vpl.txt. Do not edit. */\n' +
    'window.FC_CONTENT = ' + JSON.stringify(out, null, 1) + ';\n';
}

module.exports = { build, loadBible, passage, parseRef, plain, trimQuotes, TITLES, BOOKS };

if (require.main === module) {
  const js = build();
  const target = path.join(ROOT, '..', '..', 'app', 'www', 'modules', 'faith', 'content.js');
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (cur !== js) { console.error('content.js is out of date: run node modules/faith/tools/build-content.cjs'); process.exit(1); }
    console.log('content.js up to date');
  } else {
    fs.writeFileSync(target, js);
    console.log('wrote app/www/modules/faith/content.js (' + js.length + ' bytes)');
  }
}
