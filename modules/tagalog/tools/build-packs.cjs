#!/usr/bin/env node
/* Bundles modules/tagalog/packs/*.json into app/www/modules/tagalog/tl-packs.js (packs that ship inside the app)
   and writes modules/tagalog/packs/index.json (the list the app reads from GitHub to download newer weeks).
   Usage: node modules/tagalog/tools/build-packs.cjs [--check] */
'use strict';
const fs = require('fs'); const path = require('path');
const SRC = path.join(__dirname, '..', 'packs');
const OUT = path.join(__dirname, '..', '..', '..', 'app', 'www', 'modules', 'tagalog');
const V = require('../../../app/www/modules/tagalog/tagalog-core.js');
const packs = fs.readdirSync(SRC).filter((f) => /^\d{4}-\d\d-\d\d\.json$/.test(f)).sort().map((f) => {
  const p = JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8'));
  const errs = V.checkPack(p);
  if (errs.length) { console.error(f + ':\n  ' + errs.join('\n  ')); process.exit(1); }
  return p;
});
const js = '/* Generated by modules/tagalog/tools/build-packs.cjs. Do not edit. */\nwindow.TL_PACKS = ' + JSON.stringify(packs) + ';\n';
const target = path.join(OUT, 'tl-packs.js');
const index = JSON.stringify({ packs: packs.map((p) => p.id) }, null, 1) + '\n';
if (!process.argv.includes('--check')) fs.writeFileSync(path.join(SRC, 'index.json'), index);
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== js) { console.error('tl-packs.js is out of date: run node modules/tagalog/tools/build-packs.cjs'); process.exit(1); }
  console.log('tl-packs.js up to date (' + packs.length + ' packs)');
} else {
  fs.writeFileSync(target, js);
  console.log('wrote tl-packs.js (' + packs.length + ' packs)');
}
